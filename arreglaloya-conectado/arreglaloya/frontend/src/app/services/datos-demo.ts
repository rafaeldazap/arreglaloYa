// Fecha y hora a partir de hoy, en el formato de <input type="datetime-local">
function dia(offset: number, hora = '09:00'): string {
  const d = new Date();
  d.setDate(d.getDate() + offset);
  return `${d.toISOString().slice(0, 10)}T${hora}`;
}

